"""Generate the Lean files of the linear-programming part of the p^2 q^2 proof from certificates_p2q2.json.
Output (in /home/agent2/lean/pqr/P2q2/): Atoms.lean, OfG.lean, CertsA<k>.lean, CertsB<k>.lean, DispatchA.lean, DispatchB.lean."""
import json, sys, itertools, sympy as sp
OUT='/home/agent2/lean/pqr/P2q2/'
p,q=sp.symbols('p q',positive=True)
s_,t_=sp.symbols('s t',nonnegative=True)
CLS=[(i,j) for i in range(3) for j in range(3)]
def cc(P,l,i): return [[P**2-P,P-1,1],[-P,P-1,1],[0,-1,1]][l][i]
m={c:sp.Symbol('m%d%d'%c) for c in CLS}
gm={(a,b):sum(m[(i,j)] for i in range(a+1) for j in range(b+1)) for (a,b) in CLS}          # gamma_ab in Moebius coordinates
Lm={(l,k):sum(m[(i,j)]*p**(2-i)*q**(2-j) for i in range(l,3) for j in range(k,3)) for (l,k) in CLS}
G={c:sp.Symbol('G%d%d'%c) for c in CLS}
LG={(l,k):sum(G[(i,j)]*cc(p,l,i)*cc(q,k,j) for (i,j) in CLS) for (l,k) in CLS}             # Lambda_lk in gamma coordinates
for o in CLS: assert sp.expand(LG[o].subs({G[c]:gm[c] for c in CLS})-Lm[o])==0              # the two descriptions agree

# ---------- atoms (positive forms) ----------
COMMON=[p,q,p-1,q-1,q-p,p+1,q+1,p+q,p+q+1,2*p*q-p**2-q,p*q-1,p**2*q-p**2-p*q+q,q**2-p,p*q**2-p*q+p-q**2,2*p*q-p-q,
        p**2-p*q-p+q**2-q+1,p**2*q-p**2+p*q**2-q**2,p*q+p-p**2-1,p**2+p*q**2-p*q-q**2,2*p*q**2-p**2-q**2,
        2*p*q**2-p**2*q+p**2-p*q-q**2,p**2*q**2-p**2*q+p**2-p*q**2-p*q+q**2,q**2-q+1-p,2*q-p-1,p*q-p-q]
REG={'A':[p**2-q,2*p**2*q-p**2-q**2],'B':[q-p**2]}
def rat(c):
    c=sp.Rational(c); return str(c.p) if c.q==1 else '(%d/%d)'%(c.p,c.q)
def poly(e,par=True):
    """Lean string of a polynomial in p, q (expanded)."""
    e=sp.expand(e)
    if e==0: return '0'
    out=[]
    for (a,b),c in sp.Poly(e,p,q).terms():
        mon=[]
        if a: mon.append('p' if a==1 else 'p^%d'%a)
        if b: mon.append('q' if b==1 else 'q^%d'%b)
        if not mon: st=rat(abs(c))
        elif abs(c)==1: st='*'.join(mon)
        else: st=rat(abs(c))+'*'+'*'.join(mon)
        out.append(('-' if c<0 else '+',st))
    res=('-' if out[0][0]=='-' else '')+out[0][1]
    for sg,st in out[1:]: res+=' %s %s'%(sg,st)
    return '('+res+')' if (par and (len(out)>1 or out[0][0]=='-')) else res
ATOMSTR={}
def atom_string(a): return 'p' if a==p else ('q' if a==q else poly(a))
def find_atom(g,regime):
    for a in COMMON+REG[regime]:
        if sp.expand(g-a)==0: return a,1
        if sp.expand(g+a)==0: return a,-1
    raise KeyError('unknown atom %s in regime %s'%(g,regime))
def factored(e,regime):
    """Lean string of a rational function as (constant * product of atoms) / (product of atoms); returns (string, sign, set of den atoms)."""
    e=sp.together(sp.simplify(e))
    if e==0: return '0',0,set()
    num,den=sp.fraction(e)
    sg=1; parts=[]; dens=set()
    c1,f1=sp.factor_list(num); c2,f2=sp.factor_list(den)
    const=sp.Rational(c1)/sp.Rational(c2)
    if const<0: sg=-sg; const=-const
    def prod(facs,isden):
        nonlocal sg
        out=[]
        for g,mult in facs:
            a,sgn=find_atom(g,regime)
            if sgn<0 and mult%2==1: sg=-sg
            if isden: dens.add(a)
            out.append(atom_string(a) if mult==1 else '%s^%d'%(atom_string(a),mult))
        return out
    nums=prod(f1,False); dn=prod(f2,True)
    top='*'.join(([rat(const)] if (const!=1 or not nums) else [])+nums)
    st=top if not dn else '%s/(%s)'%(top if len(nums)+ (const!=1)<=1 else '('+top+')','*'.join(dn))
    return st,sg,dens

def atoms_file():
    L=['/- GENERATED by ~/p2q2/leangen/gen.py.  The polynomial sign facts used by the certificates. -/','import Mathlib','','namespace P2q2','',
       '/-- sign facts valid for all real `2 ≤ p`, `p + 1 ≤ q` -/','structure Atoms (p q : ℝ) : Prop where']
    for i,a in enumerate(COMMON): L.append('  a%d : 0 < %s'%(i,atom_string(a) if a in (p,q) else poly(a,par=False)))
    L+=['','theorem atoms_of (p q : ℝ) (hp : 2 ≤ p) (hpq : p + 1 ≤ q) : Atoms p q := by',
        '  have hs : 0 ≤ p - 2 := by linarith','  have ht : 0 ≤ q - p - 1 := by linarith','  refine ⟨?_'+', ?_'*(len(COMMON)-1)+'⟩']
    for a in COMMON:
        e=sp.expand(a.subs({q:p+1+t_}).subs({p:2+s_})); P_=sp.Poly(e,s_,t_)
        assert all(c>0 for c in P_.coeffs()) and e.subs({s_:0,t_:0})>0, a
        terms=[]
        for (i,j),c in P_.terms():
            f=[rat(c)]+(['(p - 2)'+('^%d'%i if i>1 else '')] if i else [])+(['(q - p - 1)'+('^%d'%j if j>1 else '')] if j else [])
            terms.append('*'.join(f))
        L.append('  · have e : %s = %s := by ring'%(poly(a,par=False),' + '.join(terms)))
        L.append('    rw [e]; positivity')
    L+=['','end P2q2','']
    open(OUT+'Atoms.lean','w').write('\n'.join(L))

def ofg_file():
    names=['g%d%d'%c for c in CLS]
    L=['/- GENERATED by ~/p2q2/leangen/gen.py.  A point of the programme given by its values on the nine classes. -/','import P2q2.LPDefs','','namespace P2q2','','namespace Nine','',
       '/-- the nine Möbius coefficients of the step function with values `gab` on the classes -/',
       'def ofG ('+' '.join(names)+' : ℝ) : Nine :=',
       '  ⟨g00, g01 - g00, g02 - g01, g10 - g00, g11 - g10 - g01 + g00, g12 - g11 - g02 + g01, g20 - g10,',
       '   g21 - g20 - g11 + g10, g22 - g21 - g12 + g11⟩','']
    args=' '.join(names)
    for c in CLS:
        L.append('theorem g%d%d_ofG (%s : ℝ) : (ofG %s).g%d%d = g%d%d := by'%(c+(args,args)+c+c)); L.append('  first | (simp only [ofG, Nine.g%d%d]; ring) | simp only [ofG, Nine.g%d%d]'%(c+c))
    for o in CLS:
        expr=' + '.join('%s*%s*g%d%d'%(poly(cc(p,o[0],i)),poly(cc(q,o[1],j)),i,j) for (i,j) in CLS if cc(p,o[0],i)!=0 and cc(q,o[1],j)!=0)
        L.append('theorem L%d%d_ofG (p q %s : ℝ) : (ofG %s).L%d%d p q = %s := by'%(o+(args,args)+o+(expr,))); L.append('  first | (simp only [ofG, Nine.L%d%d]; ring) | simp only [ofG, Nine.L%d%d]'%(o+o))
    L+=['','end Nine','','end P2q2','']
    open(OUT+'OfG.lean','w').write('\n'.join(L))

if __name__=='__main__':
    atoms_file(); ofg_file(); print('Atoms.lean, OfG.lean written')
