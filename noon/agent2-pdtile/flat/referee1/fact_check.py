"""Referee check of Facts 1, 2, 3 of Section 6.

Both sides of each Fact are LINEAR conditions on the weight vector w in Q^M (w = indicator of A).
So each Fact is the statement  ker(L_cyc) = ker(L_counts).  We prove that exactly, per (M, d):
  (1) L_counts annihilates every cyclic shift X^k Phi_d mod (X^M - 1); these shifts span ker(L_cyc)
      (the ideal generated by Phi_d in Q[X]/(X^M-1)), so ker(L_cyc) <= ker(L_counts);   [exact integers]
  (2) rank(L_counts) >= phi(d) = codim ker(L_cyc); rank over GF(P) is a lower bound for rank over Q.
Then, separately, the literal test asked for: random and structured sets, floating-point evaluation of
A at roots of unity versus the count condition as worded in the document.
"""
import itertools
import math
import random
import sys

import numpy as np

from cyclo import cyclotomic, phi, divisors, rank_mod, divides_numeric, divides_exact


def factor2(M):
    f = {}
    n = M
    k = 2
    while n > 1:
        while n % k == 0:
            f[k] = f.get(k, 0) + 1
            n //= k
        k += 1
    return f


def shifts_of_phi(M, d):
    ph = cyclotomic(d)
    G = np.zeros((M, M), dtype=np.int64)  # column k = X^k Phi_d mod X^M-1
    for k in range(M):
        for i, c in enumerate(ph):
            G[(k + i) % M, k] += c
    return G


def count_matrix(M, m1, m2):
    """Rows indexed by (r,t): N(r,t) = sum of w_x with x = r mod m1, x = t mod m2."""
    C = np.zeros((m1, m2, M), dtype=np.int64)
    for x in range(M):
        C[x % m1, x % m2, x] = 1
    return C


def fact2_rows(M, p, a, q, b):
    """The condition exactly as worded in Fact 2: for all r, t, i the difference
    N(r+i p^(a-1), t') - N(r, t') is the same for all t' in t + q^(b-1) Z."""
    pa, qb = p ** a, q ** b
    C = count_matrix(M, pa, qb)
    rows = []
    for r in range(pa):
        for i in range(1, p):
            r2 = (r + i * p ** (a - 1)) % pa
            for t in range(qb):
                for j in range(1, q):
                    t2 = (t + j * q ** (b - 1)) % qb
                    rows.append((C[r2, t2] - C[r, t2]) - (C[r2, t] - C[r, t]))
    return np.array(rows, dtype=np.int64)


def fact1_rows(M, p, a):
    pa = p ** a
    C = count_matrix(M, pa, 1)[:, 0, :]
    rows = []
    for r in range(pa):
        for i in range(1, p):
            rows.append(C[(r + i * p ** (a - 1)) % pa] - C[r])
    return np.array(rows, dtype=np.int64)


def kernel_equal(M, d, L):
    G = shifts_of_phi(M, d)
    incl = not np.any(L @ G)
    rk = rank_mod(L)
    return incl, rk, phi(d)


def linear_checks():
    ok = True
    for M in (12, 36, 72, 108, 144, 200, 225, 324, 400):
        f = factor2(M)
        (p, al), (q, be) = sorted(f.items())
        for (P, AL, Q, BE) in ((p, al, q, be), (q, be, p, al)):
            # Fact 1 for prime powers of P
            for a in range(1, AL + 1):
                incl, rk, ph = kernel_equal(M, P ** a, fact1_rows(M, P, a))
                good = incl and rk >= ph
                ok &= good
                if not good:
                    print("FACT 1 FAILS", M, P ** a, incl, rk, ph)
            # Fact 2, with the roles of the two primes as worded and swapped
            for a in range(1, AL + 1):
                for b in range(1, BE + 1):
                    d = P ** a * Q ** b
                    incl, rk, ph = kernel_equal(M, d, fact2_rows(M, P, a, Q, b))
                    good = incl and rk >= ph
                    ok &= good
                    if not good:
                        print("FACT 2 FAILS", M, d, incl, rk, ph)
        print(f"M={M}: Facts 1,2 kernel identity verified for every d | M of the right shape "
              f"(both orderings of the primes)", flush=True)
    return ok


def fact3_checks():
    ok = True
    for M in (36, 72, 144, 324, 400):
        f = factor2(M)
        for q in f:
            Mq = M // q
            for d in divisors(M):
                if d == 1:
                    continue
                dd = d // math.gcd(d, q)
                # L: w' in Z^{M/q} -> remainder of sum w'_x X^{qx} mod Phi_d
                from cyclo import xpow_table
                T = xpow_table(M, d)
                L = np.array([T[(q * x) % M] for x in range(Mq)], dtype=np.int64).T  # phi(d) x Mq
                assert Mq % dd == 0
                G = shifts_of_phi(Mq, dd)
                incl = not np.any(L @ G)
                rk = rank_mod(L)
                good = incl and rk >= phi(dd)
                ok &= good
                if not good:
                    print("FACT 3 FAILS", M, q, d, dd, incl, rk, phi(dd))
        print(f"M={M}: Fact 3 kernel identity verified for every d | M and each prime", flush=True)
    return ok


def fact2_literal(A, M, p, a, q, b):
    """Fact 2 exactly as worded, evaluated on a set (or multiset) A, integer arithmetic."""
    pa, qb = p ** a, q ** b
    N = np.zeros((pa, qb), dtype=np.int64)
    for x in A:
        N[x % pa, x % qb] += 1
    for r in range(pa):
        for i in range(p):
            r2 = (r + i * p ** (a - 1)) % pa
            diff = N[r2] - N[r]  # as function of t'
            for t in range(qb):
                cls = [(t + j * q ** (b - 1)) % qb for j in range(q)]
                if len(set(int(diff[c]) for c in cls)) != 1:
                    return False
    return True


def structured_set(M, d, p, a, q, b, rng):
    """A set A in Z_M with Phi_d | A: lift to Z_M of a disjoint union of cosets of the order-p and
    order-q subgroups of Z_d (each lifted element gets an arbitrary representative mod d)."""
    used = set()
    S = []
    for _ in range(rng.randint(1, 6)):
        step = d // p if rng.random() < 0.5 else d // q
        n = p if step == d // p else q
        c = rng.randrange(d)
        coset = [(c + k * step) % d for k in range(n)]
        if any(y in used for y in coset):
            continue
        used.update(coset)
        S += coset
    A = set()
    for y in S:
        x = y + d * rng.randrange(M // d)
        A.add(x)
    return sorted(A)


def literal_checks(seed=20261119):
    rng = random.Random(seed)
    ok = True
    for M in (36, 72, 144, 400):
        f = factor2(M)
        (p, al), (q, be) = sorted(f.items())
        for a in range(1, al + 1):
            for b in range(1, be + 1):
                d = p ** a * q ** b
                seen = {True: 0, False: 0}
                bad = 0
                trials = []
                for _ in range(60):
                    trials.append(structured_set(M, d, p, a, q, b, rng))
                for _ in range(60):  # perturbed structured sets: move one element
                    A = structured_set(M, d, p, a, q, b, rng)
                    A = set(A)
                    A.discard(rng.choice(sorted(A)))
                    A.add(rng.randrange(M))
                    trials.append(sorted(A))
                for _ in range(60):  # uniformly random sets
                    k = rng.randint(1, min(M, 24))
                    trials.append(sorted(rng.sample(range(M), k)))
                for A in trials:
                    lhs = divides_numeric(A, d)
                    assert lhs == divides_exact(A, M, d)
                    rhs = fact2_literal(A, M, p, a, q, b)
                    rhs_sw = fact2_literal(A, M, q, b, p, a)
                    seen[lhs] += 1
                    if lhs != rhs or lhs != rhs_sw:
                        bad += 1
                ok &= bad == 0
                print(f"M={M} d={d}: {len(trials)} sets, divisible {seen[True]}, not {seen[False]}, "
                      f"disagreements with Fact 2 (either ordering): {bad}", flush=True)
    return ok


def exhaustive_small():
    ok = True
    for M, ds in ((12, ((6, 2, 1, 3, 1), (12, 2, 2, 3, 1))), (18, ((6, 2, 1, 3, 1), (18, 2, 1, 3, 2)))):
        for (d, p, a, q, b) in ds:
            bad = 0
            tot = 0
            pos = 0
            for mask in range(1 << M):
                A = [x for x in range(M) if mask >> x & 1]
                lhs = divides_exact(A, M, d) if A else True
                rhs = fact2_literal(A, M, p, a, q, b)
                tot += 1
                pos += lhs
                bad += lhs != rhs
            ok &= bad == 0
            print(f"exhaustive: all {tot} subsets of Z_{M}, d={d}: {pos} divisible, disagreements {bad}",
                  flush=True)
    return ok


if __name__ == "__main__":
    r1 = linear_checks()
    r3 = fact3_checks()
    r2 = literal_checks()
    r4 = exhaustive_small() if "--exhaustive" in sys.argv else None
    print("LINEAR (Facts 1,2):", r1, " FACT 3:", r3, " LITERAL:", r2, " EXHAUSTIVE:", r4)
