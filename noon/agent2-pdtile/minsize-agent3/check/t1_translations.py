def random_multiset(p, q, n, kind):
    M = p ** n * q
    w = [0] * M
    if kind == 'plain':
        for _ in range(random.randint(1, 3 * M)):
            w[random.randrange(M)] += 1
    elif kind == 'sparse':
        for _ in range(random.randint(1, 6)):
            w[random.randrange(M)] += random.randint(1, 3)
    else:
        # sums of translates of cosets of subgroups (their mask polynomials have many cyclotomic divisors),
        # optionally plus a few single points
        divs = [d for d in range(2, M + 1) if M % d == 0]
        for _ in range(random.randint(1, 4)):
            r = random.choice(divs)            # subgroup of order r, generated by M/r
            t = random.randrange(M)
            m = random.randint(1, 2)
            for j in range(r):
                w[(t + j * (M // r)) % M] += m
        if kind == 'cosets+points':
            for _ in range(random.randint(1, 3)):
                w[random.randrange(M)] += 1
        if kind == 'product':
            # multiply (cyclically) by another sum of cosets: gives equidistribution at several levels at once
            v = [0] * M
            for _ in range(random.randint(1, 2)):
                r = random.choice(divs); t = random.randrange(M)
                for j in range(r):
                    v[(t + j * (M // r)) % M] += 1
            out = [0] * M
            for a, x in enumerate(w):
                if x:
                    for b, y in enumerate(v):
                        if y: out[(a + b) % M] += x * y
            w = out
    return w


def facts(p, q, n, w, E, F):
    """(i) p^e | |A|, and q | |A| if balanced; (ii) children of equal shape: totals differ by multiples of q;
    (iii) unbalanced class with children of equal shapes: every child unbalanced (hence nonempty)."""
    size = sum(w)
    assert size % (p ** len(E)) == 0
    if 0 in F: assert size % q == 0
    for a in range(1, n + 1):
        par = p ** (a - 1)
        g = class_vectors(p, q, n, w, a)
        gp = class_vectors(p, q, n, w, a - 1)
        for c in range(par):
            kids = [g[c + i * par] for i in range(p)]
            same_shape = all(len(set(v[j] - kids[0][j] for j in range(q))) == 1 for v in kids)
            if same_shape:
                assert all((sum(v) - sum(kids[0])) % q == 0 for v in kids)
                if len(set(gp[c])) != 1:           # the class is unbalanced
                    assert all(len(set(v)) != 1 for v in kids)
                    assert all(sum(v) > 0 for v in kids)


