"""Referee's own tools (26 Nov 2026).  Nothing here is taken from gen.py or from the searcher's programs.

Divisibility by a cyclotomic polynomial is tested WITHOUT cyclotomic polynomials, by the cuboid criterion:
    Phi_d | A(X)   iff   A(X) * prod_{p | d} (1 - X^{d/p})  =  0   mod  X^d - 1          (d > 1)
(X^d - 1 = Phi_d * prod_{e | d, e < d} Phi_e; the product of the 1 - X^{d/p} is divisible by every Phi_e with e | d, e < d,
and is prime to Phi_d.)  A second, separate test by exact remainder modulo Phi_d built from the Moebius product is in
divides_by_remainder(), used only to cross-check the first.
"""
import itertools, math
from functools import lru_cache


def prime_factors(n):
    f, p = [], 2
    while p * p <= n:
        if n % p == 0:
            f.append(p)
            while n % p == 0: n //= p
        p += 1
    if n > 1: f.append(n)
    return f


def divisors(M):
    return [d for d in range(1, M + 1) if M % d == 0]


def fold(A, d):
    """A mod d: list of length d."""
    B = [0] * d
    for x, w in enumerate(A):
        if w: B[x % d] += w
    return B


def cuboid_rows(M, d):
    """The d linear forms (as dicts x -> coefficient over Z_M) whose vanishing is Phi_d | A.  Row t is the coefficient of X^t in
    A(X) * prod_{p | d}(1 - X^{d/p}) mod X^d - 1."""
    ps = prime_factors(d)
    kern = {0: 1}                                   # prod (1 - X^{d/p}) mod X^d - 1
    for p in ps:
        new = {}
        for e, c in kern.items():
            new[e] = new.get(e, 0) + c
            e2 = (e + d // p) % d
            new[e2] = new.get(e2, 0) - c
        kern = {e: c for e, c in new.items() if c}
    rows = []
    for t in range(d):
        r = {}
        for e, c in kern.items():                   # coefficient of X^t gets A_d(t - e) * c
            y = (t - e) % d
            for x in range(y, M, d): r[x] = r.get(x, 0) + c
        rows.append(r)
    return rows


def divides(M, d, A):
    """Phi_d | A(X), by the cuboid criterion (exact integers)."""
    if d == 1: return sum(A) == 0
    B = fold(A, d)
    for p in prime_factors(d):
        s = d // p
        B = [B[t] - B[(t - s) % d] for t in range(d)]
    return not any(B)


def pattern(M, A):
    return [d for d in divisors(M) if d > 1 and divides(M, d, A)]


# ---- second route, for cross-checks only: Phi_d from the Moebius product, exact remainder
def _mul(a, b):
    r = [0] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        if x:
            for j, y in enumerate(b): r[i + j] += x * y
    return r


def _divexact(a, b):
    a = a[:]; q = [0] * (len(a) - len(b) + 1)
    for k in range(len(q) - 1, -1, -1):
        c = a[k + len(b) - 1] // b[-1]; q[k] = c
        for t, y in enumerate(b): a[k + t] -= c * y
    assert not any(a)
    return q


def mobius(n):
    r = 1
    for p in prime_factors(n):
        if n % (p * p) == 0: return 0
        r = -r
    return r


@lru_cache(None)
def cyclotomic(d):
    num, den = [1], [1]
    for e in divisors(d):
        mu = mobius(d // e)
        f = [-1] + [0] * (e - 1) + [1]
        if mu == 1: num = _mul(num, f)
        elif mu == -1: den = _mul(den, f)
    return tuple(_divexact(num, den))


def divides_by_remainder(M, d, A):
    phi = cyclotomic(d); a = list(A)
    for k in range(len(a) - 1, len(phi) - 2, -1):
        c = a[k]
        if c:
            for t, y in enumerate(phi): a[k - (len(phi) - 1) + t] -= c * y
    return not any(a)


# ---- up-sets and corners
def is_upset(M, D):
    dv = divisors(M)
    return all(e in D for d in D for e in dv if e % d == 0)


def upsets(M):
    """All up-sets D of the divisors of M with 1 not in D (as sorted tuples), by brute force over antichains."""
    dv = [d for d in divisors(M) if d > 1]
    out = set()
    # an up-set is generated by an antichain; enumerate subsets of divisors as generators (small lattices only)
    def gen(gens):
        return tuple(sorted(e for e in dv if any(e % g == 0 for g in gens)))
    for k in range(0, len(dv) + 1):
        for gens in itertools.combinations(dv, k):
            if any(a != b and b % a == 0 for a in gens for b in gens): continue
            out.add(gen(gens))
    return sorted(out, key=lambda D: (len(D), D))


def corners(M, D):
    Ds = set(D)
    comp = [c for c in divisors(M) if c not in Ds]
    return [c for c in comp if not any(e != c and e % c == 0 for e in comp)]


def largest_upset_inside(M, P):
    Ps = set(P); dv = divisors(M)
    return tuple(sorted(d for d in Ps if all(e in Ps for e in dv if e % d == 0)))


def coset(M, c, x):
    """indicator (list) of x + cZ_M"""
    A = [0] * M
    for y in range(x % c, M, c): A[y] = 1
    return A


def corner_cosets(M, D):
    """all cosets of cZ_M, c a corner of D, as (c, x, frozenset of points)"""
    out = []
    for c in corners(M, D):
        for x in range(c):
            out.append((c, x, frozenset(range(x, M, c))))
    return out


