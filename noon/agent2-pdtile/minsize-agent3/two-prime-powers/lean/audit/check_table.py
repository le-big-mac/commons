"""Compare Lean's evaluation of IsUpSet (bounded form) and corners with an independent program.

Reads A6_table.out, lines  M|D|isUp|corners|sum .  The definitions here are written from the intended
mathematics, not from the Lean text:
  up-set: a set of divisors of M, none equal to 1, containing with d every multiple of d that divides M;
  corners: the divisors of M not in D that are maximal for divisibility among those.
Also enumerates the up-sets of the divisor lattice by another route (as complements of down-sets generated
by antichains) and checks that Lean's list of up-sets is exactly that list.
"""
import sys, ast, itertools, collections

def divisors(M):
    return [d for d in range(1, M + 1) if M % d == 0]

def is_upset_intended(M, D):
    dv = set(divisors(M))
    if not set(D) <= dv:
        return False
    if 1 in D:
        return False
    for d in D:
        for e in dv:
            if e % d == 0 and e not in D:
                return False
    return True

def corners_intended(M, D):
    non = [d for d in divisors(M) if d not in D]
    out = []
    for c in non:
        # maximal: no other non-member is a proper multiple of c
        if not any(e != c and e % c == 0 for e in non):
            out.append(c)
    return sorted(out)

def upsets_by_antichains(M):
    """all up-sets without 1, generated another way: D = divisors not dividing any element of an antichain A
    (A nonempty), i.e. the complement of the down-set generated by A"""
    dv = divisors(M)
    res = set()
    for k in range(1, len(dv) + 1):
        for A in itertools.combinations(dv, k):
            if any(a != b and b % a == 0 for a in A for b in A):
                continue
            down = {d for d in dv if any(a % d == 0 for a in A)}
            res.add(frozenset(set(dv) - down))
    return res

rows = collections.defaultdict(list)
n = 0
bad = 0
for line in open(sys.argv[1], encoding='utf-8'):
    line = line.strip()
    if not line:
        continue
    Ms, Ds, ups, cs, sm = line.split('|')
    M = int(Ms); D = ast.literal_eval(Ds); up = (ups == 'true'); C = ast.literal_eval(cs); S = int(sm)
    n += 1
    my_up = is_upset_intended(M, set(D))
    my_C = corners_intended(M, set(D))
    my_S = sum(M // c for c in my_C)
    ok = (my_up == up) and (my_C == C) and (my_S == S) and all(M % c == 0 for c in C)
    if not ok:
        bad += 1
        if bad < 20:
            print('MISMATCH', line, my_up, my_C, my_S)
    rows[M].append((frozenset(D), up, tuple(C), S))

print('lines read:', n, ' mismatches:', bad)
print()
print('M   subsets  up-sets(Lean)  up-sets(antichain route)  same list  corner sums of the up-sets (sorted)')
for M in sorted(rows):
    dv = set(divisors(M))
    lean_up = {D for (D, up, C, S) in rows[M] if up}
    alt = upsets_by_antichains(M) if len(dv) <= 15 else None
    sums = sorted(S for (D, up, C, S) in set(rows[M]) if up)
    # every Lean up-set is a subset of the divisors
    assert all(D <= dv for D in lean_up)
    print(M, len(set(D for (D, _, _, _) in rows[M])), len(lean_up), len(alt), lean_up == alt, sums)

# what corners gives on sets that are not up-sets: still the maximal divisors outside D (checked above for all
# lines); a few examples
print()
print('examples of sets that are not up-sets (Lean says false) and what corners gives:')
shown = 0
for M in (12, 18):
    for (D, up, C, S) in rows[M]:
        if not up and shown < 12 and len(D) in (1, 2):
            print('  M=%d D=%s corners=%s sum=%d' % (M, sorted(D), list(C), S)); shown += 1
