"""Writes a Lean file that evaluates live, rank (Pnq/SignDefs.lean) and mu on small data, and what my own
transcriptions in ecore.py give (they are what the tests of S1', S2', A' use).
usage: a5_gen.py OUT.lean EXPECTED.txt"""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import random
from ecore import live, rank, mu

random.seed(55)
out, exp = sys.argv[1], sys.argv[2]
lines = ["import Pnq.SignDefs", "/-! Generated by a5_gen.py of the audit: values of `live`, `rank`, `μ`. -/", "open Pnq", ""]
exp_lines = []
cid = 0
for trial in range(60):
    p = random.choice([2, 2, 5, 5, 7, 3, 11])
    m = random.randint(0, 9)
    imax = 3 if p <= 5 else 2
    N = p ** imax
    style = trial % 3
    if style == 0:
        e = [random.randrange(0, 2 * N) for _ in range(m)]
    elif style == 1:
        L = p ** random.randint(0, imax - 1)
        c = random.randrange(0, L)
        e = [(c + t * L) % (2 * N) for t in range(p)][:9] + [random.randrange(0, N) for _ in range(random.randint(0, 2))]
    else:
        base = [random.randrange(0, N) for _ in range(2)]
        e = [random.choice(base) + random.choice([0, p, p * p]) for _ in range(m)]
    m = len(e)
    fam = "(![" + ", ".join(str(x) for x in e) + f"] : Fin {m} → ℕ)" if m else "(![] : Fin 0 → ℕ)"
    lines.append(f"#eval IO.println s!\"C{cid} {{(List.range {imax + 2}).map fun i => live {fam} {p} i}} "
                 f"{{(List.range {imax + 2}).map fun i => rank {fam} {p} i}}\"")
    lv = [live(e, p, i) for i in range(imax + 2)]
    rk = [rank(e, p, i) for i in range(imax + 2)]
    exp_lines.append(f"C{cid} {str(lv).lower()} {rk}  # e={e} p={p}")
    cid += 1
ts = list(range(0, 400)) + [5 ** 4, 5 ** 3 * 7 ** 2, 7 ** 3 * 11, 13 ** 2 * 5, 5 * 7 * 11 * 13, 25 * 49, 17 ** 2, 3 ** 5 * 5, 2 ** 10 * 7]
lines.append(f"#eval IO.println s!\"C{cid} {{({ts} : List ℕ).map μ}}\"")
exp_lines.append(f"C{cid} {[mu(t) for t in ts]}  # mu")
open(out, 'w').write("\n".join(lines) + "\n")
open(exp, 'w').write("\n".join(exp_lines) + "\n")
print(cid + 1, "cases written")
