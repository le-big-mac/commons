# Writes a Lean file that evaluates the two cardinalities of U on small families (decidable groups), and the numbers
# that my word-for-word program (u_test.py) gives for the same families.
# usage: python u_gen.py OUT.lean EXPECTED.txt
import sys, os, random
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import u_test as U

LEAN_TYPE = {'Z': 'ℤ', 'Z/2': 'ZMod 2', 'Z/3': 'ZMod 3', 'Z/4': 'ZMod 4', 'Z^2': 'ℤ × ℤ'}

def lit(g, v):
    if g == 'Z^2':
        return f"(({v[0]} : ℤ), ({v[1]} : ℤ))"
    return f"({v[0]} : {LEAN_TYPE[g]})"

def vec(items):
    return "![" + ", ".join(items) + "]"

HEADER = '''import Pnq.EvenUnion
/-! Generated by u_gen.py of the audit: the two cardinalities of U on small families, evaluated by Lean. -/
open Pnq
instance auditLevelBadDec {ι V : Type} [Fintype ι] [AddCommGroup V] [DecidableEq V]
    (pos : ι → ℕ) (val : ι → V) (ε : ι → Bool) : (j : ℕ) → Decidable (levelBad pos val ε j)
  | 0 => inferInstanceAs (Decidable (∑ k, sg (ε k) • val k = 0))
  | j + 1 => inferInstanceAs (Decidable (∀ r, r < 2 ^ j →
      csum pos val ε (2 ^ (j + 1)) r = csum pos val ε (2 ^ (j + 1)) (r + 2 ^ j)))
/-- the left side of U, with instances that can be run -/
def cntL {m c : ℕ} {V : Type} [AddCommGroup V] [DecidableEq V] (pos : Fin m → ℕ) (val : Fin c → Fin m → V)
    (K : ℕ) : ℕ :=
  (Finset.univ.filter fun ε : Fin m → Bool => ∃ c, ∃ j, j ≤ K ∧ levelBad pos (val c) ε j).card
/-- the right side of U (without the factor 2), with instances that can be run -/
def cntR {m c : ℕ} {V : Type} [AddCommGroup V] [DecidableEq V] (pos : Fin m → ℕ) (val : Fin c → Fin m → V) : ℕ :=
  (Finset.univ.filter fun ε : Fin m → Bool => ∃ c, levelBad pos (val c) ε 0).card
open Classical in
/-- `cntL` is the cardinality in the statement U (which has the instances of classical logic) -/
theorem cntL_eq {m c : ℕ} {V : Type} [AddCommGroup V] [DecidableEq V] (pos : Fin m → ℕ) (val : Fin c → Fin m → V)
    (K : ℕ) : cntL pos val K =
      (Finset.univ.filter fun ε : Fin m → Bool => ∃ c, ∃ j, j ≤ K ∧ levelBad pos (val c) ε j).card := by
  unfold cntL
  refine Finset.card_bij (fun ε _ => ε) (fun ε h => ?_) (fun _ _ _ _ h => h) (fun ε h => ⟨ε, ?_, rfl⟩)
  · simpa using h
  · simpa using h
open Classical in
/-- `cntR` is the cardinality on the right of the statement U -/
theorem cntR_eq {m c : ℕ} {V : Type} [AddCommGroup V] [DecidableEq V] (pos : Fin m → ℕ) (val : Fin c → Fin m → V) :
    cntR pos val =
      (Finset.univ.filter fun ε : Fin m → Bool => ∃ c, levelBad pos (val c) ε 0).card := by
  unfold cntR
  refine Finset.card_bij (fun ε _ => ε) (fun ε h => ?_) (fun _ _ _ _ h => h) (fun ε h => ⟨ε, ?_, rfl⟩)
  · simpa using h
  · simpa using h
#print axioms cntL_eq
#print axioms cntR_eq
/-- U for families that can be run: what the statement gives for the evaluated numbers -/
theorem cntL_le {m c : ℕ} {V : Type} [AddCommGroup V] [DecidableEq V] (pos : Fin m → ℕ) (val : Fin c → Fin m → V)
    (K : ℕ) : cntL pos val K ≤ 2 * cntR pos val := by
  rw [cntL_eq, cntR_eq]
  -- the statement has the classical `DecidableEq (Fin m)` inside `Finset.univ`; `exact` does not see through that
  convert card_exists_exists_levelBad_le pos val K
-- two systems in ℤ on the positions 0, 1: values (1, 1) and (1, -1); by `decide`
example : cntL (![0, 1] : Fin 2 → ℕ) (![![(1 : ℤ), 1], ![1, -1]] : Fin 2 → Fin 2 → ℤ) 0 = 4 := by decide
example : cntR (![0, 1] : Fin 2 → ℕ) (![![(1 : ℤ), 1], ![1, 0]] : Fin 2 → Fin 2 → ℤ) = 2 := by decide
example : cntL (![0, 1] : Fin 2 → ℕ) (![![(1 : ℤ), 1], ![1, 0]] : Fin 2 → Fin 2 → ℤ) 1 = 4 := by decide
'''

def main(out_lean, out_exp):
    rng = random.Random(2711)
    fams = []
    # fixed families first
    fams.append(('Z', (0, 1), (((1,), (1,)), ((1,), (0,))), 3))
    fams.append(('Z', (0, 1), (((1,), (1,)), ((1,), (-1,))), 3))
    fams.append(('Z', (), ((), ()), 3))                      # no element, two systems
    fams.append(('Z', (0, 1, 2), (), 3))                     # no system
    fams.append(('Z/3', (0, 1), (((0,), (1,)), ((1,), (1,))), 3))
    fams.append(('Z', (5, 7, 12, 1000001), (((1,), (1,), (1,), (1,)), ((1,), (-1,), (2,), (0,))), 5))
    for it in range(54):
        gname = rng.choice(list(LEAN_TYPE)); G = U.GROUPS[gname]
        nsys = rng.choice((0, 1, 2, 2, 2, 2, 3, 4))
        m = rng.randint(0, 5)
        prange = rng.choice((2, 4, 4, 8, 16, 10 ** 6))
        pos = tuple(rng.randrange(prange) for _ in range(m))
        style = rng.randrange(3)
        vals = []
        for c in range(nsys):
            if vals and rng.random() < 0.5:
                w = list(rng.choice(vals))
                if m:
                    i = rng.randrange(m); w[i] = U.rand_val(G, rng, style)
                vals.append(tuple(w))
            else:
                vals.append(tuple(U.rand_val(G, rng, style) for _ in range(m)))
        fams.append((gname, pos, tuple(vals), rng.choice((2, 3, 4))))
    lean = [HEADER]
    exp = []
    for idx, (gname, pos, vals, Kmax) in enumerate(fams):
        G = U.GROUPS[gname]
        m = len(pos); c = len(vals); T = LEAN_TYPE[gname]
        ms = U.masks(G, pos, vals, Kmax, slow=True)
        Ls = []; R = None
        for K in range(Kmax + 1):
            L, R, _, _ = U.counts(ms, K)
            Ls.append(L)
        exp.append(f"E{idx} [{', '.join(str(x) for x in Ls)}] {R}")
        p = f"({vec([str(x) for x in pos])} : Fin {m} → ℕ)"
        v = f"({vec([vec([lit(gname, x) for x in val]) for val in vals])} : Fin {c} → Fin {m} → {T})"
        lean.append(f'#eval IO.println s!"E{idx} {{(List.range {Kmax + 1}).map (cntL {p} {v})}} {{cntR {p} {v}}}"')
    open(out_lean, 'w').write("\n".join(lean) + "\n")
    open(out_exp, 'w').write("\n".join(exp) + "\n")
    print(f"{len(fams)} families written")

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
