"""Writes a Lean file that evaluates Pnq.live, Pnq.rank, Pnq.mu, Pnq.lhsN1 (the definitions themselves, on Fin l.length)
on data chosen here, and a JSON file with the values expected from core.py.  usage: a2_gen.py OUT.lean OUT.json"""
import json
import os
import random
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import core

rng = random.Random(7)
out_lean, out_json = sys.argv[1], sys.argv[2]

# ---- families for live / rank: (list, p), levels i = 0..4 ----
fams = []
fixed = [([], 3), ([], 2), ([0], 3), ([0], 2), ([5], 1), ([5], 0), ([], 0), ([], 1), ([0, 1, 2], 3), ([0, 1, 2, 3, 6], 3),
         ([0, 1, 2, 3, 6, 9, 18], 3), ([0, 3, 5, 6, 9, 10, 12], 3), ([0, 3, 5, 6, 9, 10, 12], 5), ([0, 1, 2, 3, 4, 5], 3),
         ([0, 0, 1, 1, 2, 2], 3), ([0, 1, 2, 3, 6], 2), ([0, 1], 2), ([0, 2], 2), ([1, 3], 2), ([0, 1, 2, 3], 2),
         ([0, 1, 2, 3, 4, 5, 6], 7), ([7, 15, 23, 31, 39, 47, 55], 7), ([0, 1, 2, 3, 4], 5), ([0, 5, 10, 15, 20], 5),
         ([0, 1, 2, 4, 6], 4), ([0, 1, 2, 3, 4, 5, 6, 7], 6), ([100, 201, 302], 3), ([2, 5, 8, 11], 3), ([2, 5, 8], 3)]
fams += fixed
for _ in range(420):
    p = rng.choice([2, 2, 3, 3, 3, 5, 5, 7, 1, 4, 6])
    m = rng.randint(0, 12)
    kind = rng.random()
    if kind < 0.35:
        R = rng.choice([max(p, 2), max(p, 2) ** 2, max(p, 2) ** 3, 300, 5000])
        l = [rng.randrange(R) for _ in range(m)]
    elif kind < 0.7:                        # clustered: few classes at the top, full groups below
        pp = max(p, 2)
        base = [rng.randrange(pp ** 3) for _ in range(rng.randint(1, 2))]
        l = [rng.choice(base) + rng.randrange(pp) * pp ** rng.randint(0, 3) for _ in range(m)]
    else:                                   # progressions
        a, s = rng.randrange(50), rng.choice([1, 1, 2, 3, 5, 7, 9, 25])
        l = [a + s * k for k in range(m)]
    fams.append((l, p))
exp_fams = []
for l, p in fams:
    row = [1 if core.live(l, p, i) else 0 for i in range(5)] + [core.rank(l, p, i) for i in range(5)]
    exp_fams.append(row)

# ---- mu ----
mu_small = [core.mu(t) for t in range(3001)]
mu_big_args = [3 ** 6 * 5 ** 3 * 7 ** 2 * 11 * 13, 3 ** 20, 5 ** 9 * 7, 2 ** 10 * 3, 2 * 3 * 5 * 7 * 11 * 13 * 17 * 19 * 23,
               11025, 45045, 3 ** 5 * 5 ** 3 * 7 ** 2 * 11, 10 ** 9 + 7, 999999999989, 3 ** 18 * 5 ** 9, 29 ** 3, 31 * 37 * 41]
mu_big = [core.mu(t) for t in mu_big_args]

# ---- lhsN1 ----
def tmax(m):
    """all odd t > 1 with mu t <= m - 1, by a search over exponents of the odd primes p <= m"""
    primes = [p for p in range(3, m + 1) if all(p % q for q in range(2, p))]
    res = [1]
    for p in primes:
        res = [t * p ** v for t in res for v in range((m - 1) // (p - 1) + 1)]
    return sorted(t for t in res if t > 1)

lhs_cases = []
for m in range(1, 15):
    T = tmax(m)
    assert all(core.mu(t) + 1 <= m and t % 2 == 1 and t > 1 for t in T)
    lhs_cases.append((m, T))
lhs_cases.append((16, tmax(16)))
lhs_cases += [(m, []) for m in (0, 1, 2, 4, 12, 13, 14, 15, 16, 30)]
lhs_cases += [(m, [3]) for m in (3, 5, 6, 12, 13, 14, 15, 16)]
lhs_cases += [(m, [3, 5, 9, 15, 45]) for m in (3, 5, 6, 14)]
lhs_cases += [(14, [5, 9, 15, 45]), (14, [0, 1, 2, 3, 4, 6]), (15, [0, 1, 2, 3, 4, 6]), (2, [3, 3, 3]), (14, [9, 27, 81]),
              (20, [3, 9, 27, 81, 243, 5, 25, 125, 7, 49, 11, 13, 17, 19]), (14, [6, 12, 10]), (7, [1]), (8, [0])]
for _ in range(60):
    m = rng.randint(1, 24)
    T = sorted(set(rng.choice([3, 5, 7, 9, 11, 13, 15, 21, 25, 27, 33, 35, 45, 49, 63, 75, 81, 105, 2, 4, 1, 99, 121, 169])
                   for _ in range(rng.randint(0, 9))))
    lhs_cases.append((m, T))
exp_lhs = []
for m, T in lhs_cases:
    q = core.lhsN1(m, T)
    exp_lhs.append([q.numerator, q.denominator])

json.dump({'fams': [[l, p] for l, p in fams], 'exp_fams': exp_fams, 'mu_small': mu_small, 'mu_big_args': mu_big_args,
           'mu_big': mu_big, 'lhs_cases': [[m, T] for m, T in lhs_cases], 'exp_lhs': exp_lhs}, open(out_json, 'w'))

def lst(l):
    return '[' + ', '.join(str(x) for x in l) + ']'

L = []
L.append('import Pnq.SignFinal')
L.append('/-! Audit: values of `Pnq.live`, `Pnq.rank`, `Pnq.μ`, `Pnq.lhsN1` (the definitions themselves; a family is')
L.append('`fun k : Fin l.length => l.get k`).  Generated by `a2_gen.py`; compared with its expected values by `a2_cmp.py`. -/')
L.append('open Pnq')
L.append('def famOf (l : List ℕ) : Fin l.length → ℕ := fun k => l.get k')
L.append('def rowOf (c : List ℕ × ℕ) : List ℕ :=')
L.append('  ((List.range 5).map fun i => if live (famOf c.1) c.2 i then 1 else 0) ++')
L.append('    ((List.range 5).map fun i => rank (famOf c.1) c.2 i)')
L.append('def lhsOf (c : ℕ × List ℕ) : List ℤ := let q := lhsN1 c.1 c.2.toFinset; [q.num, (q.den : ℤ)]')
CH = 40
for a in range(0, len(fams), CH):
    chunk = fams[a:a + CH]
    body = ', '.join('((%s : List ℕ), %d)' % (lst(l), p) for l, p in chunk)
    L.append('#eval IO.println ("FAMS " ++ toString (([%s] : List (List ℕ × ℕ)).map rowOf))' % body)
L.append('#eval IO.println ("MUSMALL " ++ toString ((List.range 3001).map μ))')
L.append('#eval IO.println ("MUBIG " ++ toString (%s.map μ))' % lst(mu_big_args))
for a in range(0, len(lhs_cases), 10):
    chunk = lhs_cases[a:a + 10]
    body = ', '.join('(%d, (%s : List ℕ))' % (m, lst(T)) for m, T in chunk)
    L.append('#eval IO.println ("LHS " ++ toString (([%s] : List (ℕ × List ℕ)).map lhsOf))' % body)
open(out_lean, 'w').write('\n'.join(L) + '\n')
print('families', len(fams), 'lhs cases', len(lhs_cases), 'largest T', max(len(T) for m, T in lhs_cases))
