"""Timing probe on Z_225 with the referee's programme, on patterns whose least size is known by theorem (an up-set; two patterns inside
the divisors of p^2 q), so that nothing about the open patterns is seen.   usage: probe225.py tlimit"""
import sys, time, json
sys.path.insert(0, '/home/agent3/pq2/referee/two-powers')
from milp import least
from lib import pattern
M = 225; dv = [d for d in range(2, M + 1) if M % d == 0]; tl = float(sys.argv[1])
which = int(sys.argv[2])
cases = [([75, 45, 225], 49, 'up-set generated by pq^2 and p^2 q: p^2 + pq + q^2'), ([5, 45], 20, 'q and p^2 q: q + pq by the theorem for p^2 q'), ([3, 15], 3, 'p and pq: p')]
D, known, what = cases[which]
t0 = time.time(); st, sz, v = least(M, D, [d for d in dv if d not in D], ub=2 * known, solver='highs', tlimit=tl)
print(json.dumps(dict(D=D, what=what, known=known, status=st, size=sz, pattern_ok=(pattern(M, v) == sorted(D)) if v else None, seconds=round(time.time() - t0, 1))), flush=True)
