"""Raking bonds with one header and k stretchers in every course: how close do their headers come to a hexagonal lattice?
The centres form the lattice generated by (w, 0) and (s, a), w = 4k + 2, s odd, a = 4/3 (course height in quarters).
Covering radius of a plane lattice = circumradius of the triangle on a reduced basis.   (Noon, 21 November 2026)"""
import math
A = 4 / 3
def cover(w, s, a=A):
    u, v = (float(w), 0.0), (float(s), a)
    while True:                                           # Gauss reduction
        if u[0] ** 2 + u[1] ** 2 > v[0] ** 2 + v[1] ** 2: u, v = v, u
        m = round((u[0] * v[0] + u[1] * v[1]) / (u[0] ** 2 + u[1] ** 2))
        if m == 0: break
        v = (v[0] - m * u[0], v[1] - m * u[1])
    if u[0] * v[0] + u[1] * v[1] < 0: v = (-v[0], -v[1])
    d = (u[0] - v[0], u[1] - v[1]); n = lambda t: math.hypot(*t)
    return n(u) * n(v) * n(d) / (2 * abs(u[0] * v[1] - u[1] * v[0]))
def spread(w, s, a=A): return math.sqrt(2 * w * a / (3 * math.sqrt(3))) / cover(w, s, a)
best = 0
print(" k   w   s   share  spread   (record holders among one-header courses, any rake)")
for k in range(1, 60):
    w = 4 * k + 2; e, s = max((spread(w, s), s) for s in range(1, w // 2 + 1, 2))
    centred = spread(w, w // 2) if (w // 2) % 2 else None
    if e > best + 1e-12: best = e; print(f"{k:2d} {w:3d} {s:3d}  1/{2 * k + 1:<3d}  {e:.4f}")
print("\ncentred (header over the middle of the run below) against the best rake, k = 1..8:")
for k in range(1, 9):
    w = 4 * k + 2; e, s = max((spread(w, s), s) for s in range(1, w // 2 + 1, 2))
    print(f"  k={k} w={w}: centred (rake {w // 2}) {spread(w, w // 2):.3f};  best rake {s}: {e:.3f}")
